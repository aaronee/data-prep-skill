#!/usr/bin/env python3
"""Generate CANDIDATE gold rows for `prep.py --eval`, non-circular and
non-leaking:

  <question> | <key phrase> | <PDF page> | <chunk id>

* content chunks only (chunks tagged llm_type legal/boilerplate/notice are
  never cited; candidates are NOT taken from removed.jsonl)
* the key phrase is ONE content word that must occur in the cited chunk
* the question never contains the key phrase (no answer leakage)
* deterministic, stdlib only, no LLM

The output is a STARTING POINT: a human verifies each phrase + page, may
rewrite the questions freely, and drops rows that fail verification.
Page = PDF page (the chunk's first 'page' value), same as the v2 gold files.

Usage:
    python3 make_eval_candidates.py <name>.chunks.json [--count 20] [-o out.txt]
"""
import argparse
import json
import re

STOP = {"about", "which", "these", "their", "there", "where", "would",
        "could", "should", "other", "first", "second", "third", "being",
        "using", "used", "such", "this", "that", "with", "from", "have",
        "will", "chapter", "section", "figure", "table", "page", "book",
        "text", "line", "note", "here", "also", "more", "most", "than",
        "then", "when", "while", "much", "many", "very", "only", "some",
        "into", "over", "under", "between", "against", "through"}
BAD_TYPE = {"legal", "boilerplate", "notice"}


def content_word(text):
    """Longest alphabetic word (>=6 chars, not a stopword); deterministic
    (first in case of a tie). This is the key phrase."""
    best, best_len, seen = None, 5, set()
    for m in re.finditer(r"[A-Za-z]{6,}", text):
        w = m.group(0).lower()
        if w in STOP or w in seen:
            continue
        if len(w) > best_len:
            best, best_len = w, len(w)
        seen.add(w)
    return best


def topic_for(chunk, phrase):
    """A question topic that never contains the key phrase."""
    path = chunk.get("path") or []
    t = path[-1].strip() if path else ""
    words = [w for w in re.findall(r"[A-Za-z][A-Za-z'-]*", t)]
    if len(words) >= 2 and all(len(w) >= 3 for w in words) \
            and phrase not in {w.lower() for w in words}:
        return t
    return "the document"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("chunks")
    ap.add_argument("--count", type=int, default=20)
    ap.add_argument("-o", "--out")
    args = ap.parse_args()

    chunks = json.load(open(args.chunks, encoding="utf-8"))
    pool = [c for c in chunks if c.get("llm_type") not in BAD_TYPE
            and content_word(c["text"])]
    if not pool:
        raise SystemExit("no content chunks available")
    n = len(pool)
    k = max(1, n // args.count)
    picks, last = [], -10**9
    for i, c in enumerate(pool):
        if len(picks) >= args.count:
            break
        if i - last >= k // 2:
            picks.append(c)
            last = i
    while len(picks) < min(args.count, n):
        picks.append(pool[len(picks) % n])

    lines = [
        "# CANDIDATES — generated by make_eval_candidates.py (deterministic, no LLM).",
        "# HUMAN MUST VERIFY each key phrase + page and may rewrite the questions",
        "# before using this file with `prep.py --eval`. Page = PDF page.",
        "# Replace each leading TODO... text with a real question; --eval skips TODO rows.",
        "# Columns: question | key phrase | PDF page | chunk id",
    ]
    for c in picks:
        phrase = content_word(c["text"])
        page = c["page"][0] if c.get("page") else "?"
        excerpt = " ".join(c["text"].split())[:240]
        lines.append(f"# excerpt {c['id']} p{page}: {excerpt}")
        lines.append(f"TODO write a question answered by the excerpt above, "
                     f"never using the key phrase | {phrase} | {page} | {c['id']}")
    out = "\n".join(lines) + "\n"
    if args.out:
        open(args.out, "w", encoding="utf-8").write(out)
        print(f"wrote {len(picks)} candidates -> {args.out}")
    else:
        print(out)


if __name__ == "__main__":
    main()
